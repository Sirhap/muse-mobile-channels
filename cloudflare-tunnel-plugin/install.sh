#!/usr/bin/env bash
# Idempotent installer for the Cloudflare tunnel plugin.
# Renders the systemd units from plugin.conf, installs them, and starts
# the stack. Safe to re-run; also used as the self-heal entry point
# after a VM replacement wipes /etc/systemd/system.
set -euo pipefail

PKG="$(cd "$(dirname "$0")" && pwd)"
# shellcheck disable=SC1091
if [ ! -f "$PKG/plugin.conf" ]; then
  echo "plugin.conf missing: cp plugin.example.conf plugin.conf and fill in your values first" >&2
  exit 1
fi
source "$PKG/plugin.conf"

render() {
  sed -e "s|@HOME@|$HOME|g" \
      -e "s|@PKG@|$PKG|g" \
      -e "s|@SITE_DIR@|$SITE_DIR|g" \
      -e "s|@LOCAL_PORT@|$LOCAL_PORT|g" \
      -e "s|@TUNNEL_NAME@|$TUNNEL_NAME|g" \
      -e "s|@HOSTNAME@|$HOSTNAME|g" "$1"
}

CFG="$HOME/.cloudflared/config-$TUNNEL_NAME.yml"
if [ ! -f "$CFG" ]; then
  echo "ERROR: cloudflared config $CFG not found." >&2
  echo "Create the tunnel first (credentials are never generated by the installer):" >&2
  echo "  cloudflared tunnel login" >&2
  echo "  cloudflared tunnel create $TUNNEL_NAME" >&2
  echo "  cloudflared tunnel route dns $TUNNEL_NAME $HOSTNAME" >&2
  echo "then write $CFG with the tunnel UUID, its credentials-file and an" >&2
  echo "ingress mapping $HOSTNAME -> http://127.0.0.1:$LOCAL_PORT (see config.example.yml)." >&2
  exit 1
fi

ENV_FILE="$HOME/.config/cloudflared-relay.env"
if [ ! -f "$ENV_FILE" ]; then
  mkdir -p "$HOME/.config"
  if [ -n "${https_proxy:-${HTTPS_PROXY:-}}" ]; then
    { echo "HTTPS_PROXY=${HTTPS_PROXY:-$https_proxy}"
      echo "https_proxy=${https_proxy:-$HTTPS_PROXY}"
    } > "$ENV_FILE"
    chmod 600 "$ENV_FILE"
    echo "created $ENV_FILE from current proxy environment"
  else
    echo "ERROR: $ENV_FILE missing and no https_proxy in the environment." >&2
    echo "The relay needs the egress proxy address (with credentials) there." >&2
    exit 1
  fi
fi

UNITS="intro-site.service cloudflared-relay.service cloudflared-tunnel.service"
[ "${ENABLE_PINGGY:-0}" = "1" ] && UNITS="$UNITS pinggy-tunnel.service"
for unit in $UNITS; do
  render "$PKG/units/$unit" > "/etc/systemd/system/$unit"
  echo "installed $unit"
done

systemctl daemon-reload
for unit in $UNITS; do
  systemctl enable --now "$unit" >/dev/null 2>&1 || systemctl start "$unit" || true
done

sleep 5
"$PKG/health.sh" || true
