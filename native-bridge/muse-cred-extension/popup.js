/**
 * Muse 桥凭证导出工具 — 兼容 Chrome / Edge / Firefox (Manifest V3)
 *
 * 功能：
 * 1. 通过浏览器扩展 cookies API 读取 muse.ai 下的所有 Cookie（包含 HttpOnly），
 *    生成符合 muse_cli.gateway.load_cookies 规范的 cookies.txt。
 * 2. 在已登录的 muse.ai 标签页上下文中请求 /api/auth/check、/api/session、/api/hatch/token，
 *    获取 vm_id.txt 与 token.json。
 */

const ext = typeof browser !== 'undefined' ? browser : chrome;

const state = {
  cookies: [],
  tokenObj: null,
  vmId: ''
};

/**
 * 将回调或 Promise 风格的 WebExtension API 统一包装为 Promise
 */
function callExtApi(fn, ...args) {
  return new Promise((resolve, reject) => {
    try {
      const maybePromise = fn(...args, (result) => {
        const lastError = ext.runtime && ext.runtime.lastError;
        if (lastError) {
          reject(new Error(lastError.message || String(lastError)));
        } else {
          resolve(result);
        }
      });
      if (maybePromise && typeof maybePromise.then === 'function') {
        maybePromise.then(resolve, reject);
      }
    } catch (err) {
      reject(err);
    }
  });
}

/**
 * 读取 muse.ai 及其子域的所有 Cookie（包含 HttpOnly）
 */
async function fetchMuseCookies() {
  const byDomain = await callExtApi(ext.cookies.getAll.bind(ext.cookies), {
    domain: 'muse.ai'
  });
  const byUrl = await callExtApi(ext.cookies.getAll.bind(ext.cookies), {
    url: 'https://muse.ai/'
  });
  const map = new Map();
  for (const ck of [...(byDomain || []), ...(byUrl || [])]) {
    const key = `${ck.domain}|${ck.path}|${ck.name}`;
    map.set(key, ck);
  }
  return Array.from(map.values());
}

/**
 * 将 Cookie 列表格式化为 Netscape HTTP Cookie File 或单行 Header 字符串
 */
function formatCookiesText(cookies, format) {
  if (!cookies || cookies.length === 0) {
    return '';
  }
  if (format === 'header') {
    const seen = new Map();
    for (const c of cookies) {
      seen.set(c.name, c.value);
    }
    return Array.from(seen.entries())
      .map(([k, v]) => `${k}=${v}`)
      .join('; ') + '\n';
  }
  const lines = [
    '# Netscape HTTP Cookie File',
    '# Generated by Muse Bridge Credential Exporter'
  ];
  for (const c of cookies) {
    const domain = c.hostOnly
      ? c.domain.replace(/^\./, '')
      : (c.domain.startsWith('.') ? c.domain : `.${c.domain}`);
    const includeSubdomains = domain.startsWith('.') ? 'TRUE' : 'FALSE';
    const path = c.path || '/';
    const secure = c.secure ? 'TRUE' : 'FALSE';
    const expiry = c.expirationDate ? Math.floor(c.expirationDate) : 0;
    lines.push(
      `${domain}\t${includeSubdomains}\t${path}\t${secure}\t${expiry}\t${c.name}\t${c.value}`
    );
  }
  return lines.join('\n') + '\n';
}

/**
 * 在 muse.ai 页面内执行的函数：复用浏览器同源登录态拉取 vm_id、access_token 和 hatch_token
 */
async function pageFetchMuseToken() {
  const headers = { 'Content-Type': 'application/json' };
  const parseJson = async (resp, label) => {
    if (!resp.ok) {
      const text = await resp.text();
      throw new Error(`${label} HTTP ${resp.status}: ${text.slice(0, 160)}`);
    }
    return resp.json();
  };

  const auth = await parseJson(
    await fetch('/api/auth/check', {
      method: 'POST',
      headers,
      body: '',
      credentials: 'include'
    }),
    'auth/check'
  );
  const access_token = auth.access_token;
  if (!access_token) {
    throw new Error('auth/check 未返回 access_token，请确认页面已登录');
  }

  const sess = await parseJson(
    await fetch('/api/session', { credentials: 'include' }),
    'session'
  );
  const vm_id = sess.vm_id;
  if (!vm_id) {
    throw new Error('session 未返回 vm_id（VM 可能正在启动或休眠）');
  }

  const ht = await parseJson(
    await fetch('/api/hatch/token', {
      method: 'POST',
      headers: { ...headers, Authorization: 'Bearer ' + access_token },
      body: JSON.stringify({
        vmAddress: `wss://${vm_id}.metaaivm.com/`,
        vmName: vm_id
      }),
      credentials: 'include'
    }),
    'hatch/token'
  );
  const hatch_token = ht.token;
  if (!hatch_token) {
    throw new Error('hatch/token 未返回 token');
  }

  const seg = hatch_token.split('.')[1].replace(/-/g, '+').replace(/_/g, '/');
  const payload = JSON.parse(atob(seg + '='.repeat((4 - (seg.length % 4)) % 4)));
  return {
    vm_id,
    access_token,
    hatch_token,
    issued_at: payload.iat ? new Date(payload.iat * 1000).toISOString() : null,
    issued_at_local: payload.iat ? new Date(payload.iat * 1000).toLocaleString() : null,
    exp: payload.exp ?? null
  };
}

/**
 * 查找已打开的 muse.ai 标签页并执行 Token 拉取
 */
async function fetchMuseTokenFromTab() {
  const tabs = await callExtApi(ext.tabs.query.bind(ext.tabs), {
    url: ['https://muse.ai/*', 'https://*.muse.ai/*']
  });
  if (!tabs || tabs.length === 0) {
    throw new Error('未找到已打开的 https://muse.ai 标签页，请先在浏览器中打开 muse.ai');
  }
  const activeTab = tabs.find((t) => t.active) || tabs[0];
  const results = await callExtApi(
    ext.scripting.executeScript.bind(ext.scripting),
    {
      target: { tabId: activeTab.id },
      func: pageFetchMuseToken
    }
  );
  if (!results || !results[0]) {
    throw new Error('页面脚本未返回结果');
  }
  if (results[0].error) {
    throw new Error(results[0].error.message || String(results[0].error));
  }
  return results[0].result;
}

/**
 * 触发浏览器下载二进制 Blob 或文本文件
 */
function downloadBlob(filename, blob) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}

function downloadTextFile(filename, content, mimeType = 'text/plain;charset=utf-8') {
  downloadBlob(filename, new Blob([content], { type: mimeType }));
}

/**
 * 计算 Uint8Array 的标准 CRC-32 校验值
 */
const CRC32_TABLE = (() => {
  const table = new Uint32Array(256);
  for (let i = 0; i < 256; i++) {
    let c = i;
    for (let k = 0; k < 8; k++) {
      c = (c & 1) ? (0xedb88320 ^ (c >>> 1)) : (c >>> 1);
    }
    table[i] = c >>> 0;
  }
  return table;
})();

function crc32(bytes) {
  let crc = 0xffffffff;
  for (let i = 0; i < bytes.length; i++) {
    crc = CRC32_TABLE[(crc ^ bytes[i]) & 0xff] ^ (crc >>> 8);
  }
  return (crc ^ 0xffffffff) >>> 0;
}

/**
 * 将多个文本文件在内存中打包为标准 ZIP Blob（零外部依赖，兼容 unzip / Finder / Windows）
 * @param {Array<{name: string, content: string}>} files
 */
function createZipBlob(files) {
  const encoder = new TextEncoder();
  const now = new Date();
  const dosTime =
    ((now.getHours() & 0x1f) << 11) |
    ((now.getMinutes() & 0x3f) << 5) |
    ((Math.floor(now.getSeconds() / 2)) & 0x1f);
  const dosDate =
    (((Math.max(1980, now.getFullYear()) - 1980) & 0x7f) << 9) |
    (((now.getMonth() + 1) & 0x0f) << 5) |
    (now.getDate() & 0x1f);

  const localParts = [];
  const centralParts = [];
  let offset = 0;

  for (const file of files) {
    const nameBytes = encoder.encode(file.name);
    const dataBytes = encoder.encode(file.content);
    const crc = crc32(dataBytes);
    const size = dataBytes.length;

    // Local file header (30 bytes + file name)
    const localHeader = new Uint8Array(30 + nameBytes.length);
    const lv = new DataView(localHeader.buffer);
    lv.setUint32(0, 0x04034b50, true); // Local file header signature
    lv.setUint16(4, 20, true);         // Version needed to extract (2.0)
    lv.setUint16(6, 0x0800, true);     // UTF-8 filename flag
    lv.setUint16(8, 0, true);          // Compression method: 0 (Store)
    lv.setUint16(10, dosTime, true);
    lv.setUint16(12, dosDate, true);
    lv.setUint32(14, crc, true);
    lv.setUint32(18, size, true);      // Compressed size
    lv.setUint32(22, size, true);      // Uncompressed size
    lv.setUint16(26, nameBytes.length, true);
    lv.setUint16(28, 0, true);         // Extra field length
    localHeader.set(nameBytes, 30);

    // Central directory header (46 bytes + file name)
    const centralHeader = new Uint8Array(46 + nameBytes.length);
    const cv = new DataView(centralHeader.buffer);
    cv.setUint32(0, 0x02014b50, true); // Central file header signature
    cv.setUint16(4, 20, true);         // Version made by
    cv.setUint16(6, 20, true);         // Version needed to extract
    cv.setUint16(8, 0x0800, true);     // UTF-8 filename flag
    cv.setUint16(10, 0, true);         // Compression method: 0 (Store)
    cv.setUint16(12, dosTime, true);
    cv.setUint16(14, dosDate, true);
    cv.setUint32(16, crc, true);
    cv.setUint32(20, size, true);
    cv.setUint32(24, size, true);
    cv.setUint16(28, nameBytes.length, true);
    cv.setUint16(30, 0, true);         // Extra field length
    cv.setUint16(32, 0, true);         // File comment length
    cv.setUint16(34, 0, true);         // Disk number start
    cv.setUint16(36, 0, true);         // Internal file attributes
    cv.setUint32(38, 0, true);         // External file attributes
    cv.setUint32(42, offset, true);    // Relative offset of local header
    centralHeader.set(nameBytes, 46);

    localParts.push(localHeader, dataBytes);
    centralParts.push(centralHeader);
    offset += localHeader.length + size;
  }

  const centralSize = centralParts.reduce((acc, part) => acc + part.length, 0);
  const eocd = new Uint8Array(22);
  const ev = new DataView(eocd.buffer);
  ev.setUint32(0, 0x06054b50, true);        // End of central dir signature
  ev.setUint16(4, 0, true);                 // Number of this disk
  ev.setUint16(6, 0, true);                 // Disk where central directory starts
  ev.setUint16(8, files.length, true);      // Total entries on this disk
  ev.setUint16(10, files.length, true);     // Total entries in central directory
  ev.setUint32(12, centralSize, true);      // Size of central directory
  ev.setUint32(16, offset, true);           // Offset of start of central directory
  ev.setUint16(20, 0, true);                // Comment length

  return new Blob([...localParts, ...centralParts, eocd], {
    type: 'application/zip'
  });
}

/**
 * 复制文本到剪贴板并给出临时按钮反馈
 */
async function copyWithFeedback(buttonEl, text) {
  const origText = buttonEl.textContent;
  await navigator.clipboard.writeText(text);
  buttonEl.textContent = '✅ 已复制';
  setTimeout(() => {
    buttonEl.textContent = origText;
  }, 1500);
}

function setStatus(message, isError = false) {
  const box = document.getElementById('status-box');
  if (!message) {
    box.classList.add('hidden');
    return;
  }
  box.textContent = message;
  box.classList.remove('hidden');
  box.classList.toggle('error', Boolean(isError));
}

function setBadge(text, kind) {
  const badge = document.getElementById('status-badge');
  badge.textContent = text;
  badge.className = `badge badge-${kind}`;
}

function maskToken(str) {
  if (!str || str.length < 12) return '***';
  return `${str.slice(0, 6)}...${str.slice(-4)} (len=${str.length})`;
}

function updateUI() {
  const cookieCount = state.cookies.length;
  const httpOnlyCount = state.cookies.filter((c) => c.httpOnly).length;
  const hasCookies = cookieCount > 0;
  const hasToken = Boolean(state.tokenObj && state.tokenObj.hatch_token);
  const hasVmId = Boolean(state.vmId);

  document.getElementById('cookie-stats').textContent = hasCookies
    ? `共 ${cookieCount} 项（含 ${httpOnlyCount} 个 HttpOnly）`
    : '未读取到 Cookie';

  document.getElementById('vmid-stats').textContent = hasVmId
    ? state.vmId
    : '需打开 muse.ai 页面';

  document.getElementById('token-stats').textContent = hasToken
    ? `签发于 ${state.tokenObj.issued_at_local || '刚刚'}`
    : '未读取';

  document.getElementById('btn-dl-cookies').disabled = !hasCookies;
  document.getElementById('btn-cp-cookies').disabled = !hasCookies;
  document.getElementById('btn-dl-vmid').disabled = !hasVmId;
  document.getElementById('btn-cp-vmid').disabled = !hasVmId;
  document.getElementById('btn-dl-token').disabled = !hasToken;
  document.getElementById('btn-cp-token').disabled = !hasToken;
  document.getElementById('btn-dl-all').disabled = !(hasCookies || hasVmId || hasToken);

  const summaryLines = [
    `Cookies 数量 : ${cookieCount} (HttpOnly: ${httpOnlyCount})`,
    `Cookie 键名  : ${state.cookies.map((c) => c.name).join(', ') || '无'}`,
    `VM ID        : ${state.vmId || '未获取'}`,
    `Access Token : ${state.tokenObj ? maskToken(state.tokenObj.access_token) : '未获取'}`,
    `Hatch Token  : ${state.tokenObj ? maskToken(state.tokenObj.hatch_token) : '未获取'}`,
    `签发时间     : ${state.tokenObj ? state.tokenObj.issued_at : '未获取'}`,
    '',
    '# 解压并设置权限命令（在 Muse 机器上执行）：',
    'mkdir -p ~/.config/native-bridge && chmod 700 ~/.config/native-bridge',
    'unzip -o muse-credentials.zip -d ~/.config/native-bridge',
    'chmod 600 ~/.config/native-bridge/cookies.txt ~/.config/native-bridge/vm_id.txt ~/.config/native-bridge/token.json'
  ];
  document.getElementById('summary-output').textContent = summaryLines.join('\n');
}

async function refreshAll() {
  setBadge('读取中...', 'warn');
  setStatus('');
  const errors = [];

  try {
    state.cookies = await fetchMuseCookies();
    if (state.cookies.length === 0) {
      errors.push('未检测到 muse.ai 的 Cookie，请先登录 https://muse.ai');
    }
  } catch (err) {
    errors.push(`读取 Cookie 失败：${err.message}`);
  }

  try {
    const tokenObj = await fetchMuseTokenFromTab();
    state.tokenObj = tokenObj;
    state.vmId = tokenObj.vm_id || '';
  } catch (err) {
    errors.push(`拉取 Token/vm_id 提示：${err.message}`);
  }

  updateUI();

  if (state.cookies.length > 0 && state.tokenObj) {
    setBadge('就绪', 'ok');
    setStatus('✅ 已成功读取含 HttpOnly 的完整 Cookie、vm_id 与 token.json');
  } else if (state.cookies.length > 0) {
    setBadge('仅 Cookie', 'warn');
    setStatus(errors.join('；'), false);
  } else {
    setBadge('未就绪', 'err');
    setStatus(errors.join('；'), true);
  }
}

document.addEventListener('DOMContentLoaded', () => {
  const formatSelect = document.getElementById('cookie-format');
  const getCookiesOutput = () => formatCookiesText(state.cookies, formatSelect.value);
  const getTokenOutput = () => JSON.stringify(state.tokenObj, null, 2) + '\n';
  const getVmIdOutput = () => (state.vmId ? `${state.vmId}\n` : '');

  document.getElementById('btn-fetch').addEventListener('click', refreshAll);

  document.getElementById('btn-dl-cookies').addEventListener('click', () => {
    downloadTextFile('cookies.txt', getCookiesOutput());
  });
  document.getElementById('btn-cp-cookies').addEventListener('click', (e) => {
    copyWithFeedback(e.currentTarget, getCookiesOutput());
  });

  document.getElementById('btn-dl-vmid').addEventListener('click', () => {
    downloadTextFile('vm_id.txt', getVmIdOutput());
  });
  document.getElementById('btn-cp-vmid').addEventListener('click', (e) => {
    copyWithFeedback(e.currentTarget, state.vmId);
  });

  document.getElementById('btn-dl-token').addEventListener('click', () => {
    downloadTextFile('token.json', getTokenOutput(), 'application/json;charset=utf-8');
  });
  document.getElementById('btn-cp-token').addEventListener('click', (e) => {
    copyWithFeedback(e.currentTarget, getTokenOutput());
  });

  document.getElementById('btn-dl-all').addEventListener('click', () => {
    const files = [];
    if (state.cookies.length > 0) {
      files.push({ name: 'cookies.txt', content: getCookiesOutput() });
    }
    if (state.vmId) {
      files.push({ name: 'vm_id.txt', content: getVmIdOutput() });
    }
    if (state.tokenObj && state.tokenObj.hatch_token) {
      files.push({ name: 'token.json', content: getTokenOutput() });
    }
    if (files.length === 0) return;
    const zipBlob = createZipBlob(files);
    downloadBlob('muse-credentials.zip', zipBlob);
  });

  refreshAll();
});
